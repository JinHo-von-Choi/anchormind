/** init 인자와 파일 상태 오류 */
export class InitError extends Error {
  constructor(message) {
    super(message);
    this.name = "InitError";
  }
}

const PLUGIN_NAME      = "anchormind";
const MARKETPLACE_NAME = "anchormind-local";
const PLUGIN_DIR       = `plugins/${PLUGIN_NAME}`;
const PLACEHOLDER_URL  = "https://memento.example.com/mcp";
const KEY_ENV          = "MEMENTO_CLI_KEY";
const REMOTE_ENV       = "MEMENTO_CLI_REMOTE";
const INTEGRATIONS     = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "integrations");

/**
 * 대상별 정의. source는 integrations/ 아래 플러그인 디렉터리, homeDir은 --dir 기본값의 마지막 조각이다.
 */
export const INIT_TARGETS = Object.freeze({
  claude: Object.freeze({ source: "claude-code", homeDir: "claude-code", marketplace: claudeMarketplace, nextSteps: claudeNextSteps }),
  codex : Object.freeze({ source: "codex",       homeDir: "codex",       marketplace: codexMarketplace,  nextSteps: codexNextSteps })
});

/** JSON 파일 내용(2칸 들여쓰기, 끝 줄바꿈) */
const toJson = (value) => `${JSON.stringify(value, null, 2)}\n`;

