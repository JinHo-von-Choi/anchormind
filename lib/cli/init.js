/**
 * CLI: init - 하네스 플러그인 설치 파일 생성
 *
 * 작성자: 최진호
 * 작성일: 2026-10-03
 *
 * integrations/의 Claude Code 또는 Codex 플러그인을 로컬 마켓플레이스 디렉터리 형태로 만든다.
 * 기본은 dry-run이다: 만들 파일 목록과 diff만 출력한다. --write를 주어야 쓰고, 내용이 다른 기존 파일은
 * --force 없이 덮어쓰지 않는다. --dir 아래 경로의 어느 조각이든 심볼릭 링크이거나, 최종 경로가 일반 파일이
 * 아니면 언제나 거부한다. 쓰기는 먼저 모든 위치의 쓰기 권한을 확인하고, 파일마다 임시 파일과 rename으로
 * 바꾸며, 도중에 실패하면 이번 실행의 변경을 되돌린다(_fileTransaction.js).
 *
 * API 키는 어떤 파일에도 쓰지 않는다. Claude Code 플러그인은 키를 sensitive userConfig로 받아 보안
 * 저장소에 두고, Codex는 환경 변수 이름(bearer_token_env_var)만 설정한다. 이 모듈은 lib/config.js와
 * dotenv를 가져오지 않으므로 .env를 읽지 않으며, 환경 변수를 읽지 않는다. PATH 경고에 쓰는 PATH 값은
 * 진입점이 넘기며 생성 내용에는 영향이 없다.
 */

